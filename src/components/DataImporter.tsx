export default function DataImporter({ onComplete }: { onComplete?: () => void }) {
  const [isImporting, setIsImporting] = useState(false);
  const [progress, setProgress] = useState(0);
  const [result, setResult] = useState<{ success: number; skipped: number } | null>(null);
  const { user } = useAuth();

  const parseArabicNumber = (val: string): number => {
    if (!val) return 0;
    const clean = val.replace(/,/g, '').replace(/[^\d.-]/g, '').trim();
    return parseFloat(clean) || 0;
  };

  const handleImport = async () => {
    setIsImporting(true);
    let success = 0;
    let skipped = 0;

    try {
      for (let i = 0; i < RAW_DATA.length; i++) {
        const row = RAW_DATA[i] as any;
        const requestNumber = row['رقم الطلب'];
        const defendantName = row['المنفذ ضده'];

        if (!requestNumber || !defendantName) {
          skipped++;
          continue;
        }

        // Check for duplicates first
        const q = query(collection(db, 'cases'), where('requestNumber', '==', requestNumber));
        const snap = await getDocs(q);
        if (!snap.empty) {
          skipped++;
          continue;
        }

        // Mapping Amounts
        const claimAmount = parseArabicNumber(row['مبلغ المطالبة']);
        const receivedAmount = parseArabicNumber(row['المبلغ المستلم ']);
        let remainingAmount = 0;
        const rawRem = row['المبلغ المتبقي'] || '';
        if (rawRem.includes('=') || rawRem === '') {
            remainingAmount = claimAmount - receivedAmount;
        } else {
            remainingAmount = parseArabicNumber(rawRem);
        }

        // Mapping Status
        const rawStatus = row['مراحل الطلب'] || '';
        let status = 'open';
        let statusLabel = rawStatus;
        if (rawStatus.includes('قيد التنفيذ')) {
            status = 'in_progress';
            statusLabel = 'قيد التنفيذ';
        } else if (rawStatus.includes('منتهي')) {
            status = 'closed';
            statusLabel = 'منتهي';
        } else if (rawStatus.includes('إمهال')) {
            status = 'on_hold';
            statusLabel = 'تم الإمهال';
        }

        // Mapping Decisions
        const rawDec = row['القرارات '] || '';
        let decisionCode = '';
        let decisionLabel = 'لا يوجد';
        if (rawDec.includes('34') && rawDec.includes('46')) {
            decisionCode = '34+46';
            decisionLabel = 'قرار 34 + 46';
        } else if (rawDec.includes('34')) {
            decisionCode = '34';
            decisionLabel = 'قرار 34';
        } else if (rawDec.includes('46')) {
            decisionCode = '46';
            decisionLabel = 'قرار 46';
        } else if (rawDec.includes('لا يوجد')) {
            decisionLabel = 'لا يوجد';
        } else {
            decisionCode = 'other';
            decisionLabel = rawDec;
        }

        await addDoc(collection(db, 'cases'), {
          requestType: row['نوع  الطلب'] || 'تنفيذ',
          requestNumber,
          fileDateHijri: row['تاريخ الرفع'] || '',
          subType: row['الفرعي'] || '',
          status,
          statusLabel,
          claimAmount,
          receivedAmount,
          remainingAmount,
          applicantName: row['مقدم الطلب'] || '',
          defendantName: defendantName.replace(/\|/g, '-').trim(),
          idType: row['نوع الهوية'] || '',
          legalCapacity: row['الصفة'] || '',
          nationality: row['الجنسية'] || '',
          decisionCode,
          decisionLabel,
          representativeName: row['اسم المندوب'] || '',
          clientNumber: row['رقم العميل'] || '',
          lastWithdrawalUpdate: row['اخر تحديث سحب الأموال في الحسابات '] || '',
          executionProgress: row['سير الإجراء التنفيذي الذي تم ضد المنفذ ضده '] || '',
          platform: 'ناجز',
          serialNumber: '', // Will be empty as per user request
          createdBy: user?.uid,
          createdAt: serverTimestamp(),
          updatedAt: serverTimestamp(),
        });

        success++;
        setProgress(Math.round(((i + 1) / RAW_DATA.length) * 100));
      }
      setResult({ success, skipped });
      if (onComplete) onComplete();
    } catch (error) {
      console.error('Import error:', error);
    } finally {
      setIsImporting(false);
    }
  };

  return (
    <div className="bg-white border-2 border-dashed border-indigo-100 rounded-3xl p-8 text-center" dir="rtl">
      {!result ? (
        <div className="space-y-4">
          <div className="w-16 h-16 bg-indigo-50 rounded-full flex items-center justify-center mx-auto">
            <UploadCloud size={32} className="text-indigo-600" />
          </div>
          <div>
            <h3 className="text-lg font-bold text-slate-900">استيراد القضايا من ملف CSV</h3>
            <p className="text-sm text-slate-500 mt-1">سيتم إضافة {RAW_DATA.length} قضية إلى قاعدة البيانات مباشرة.</p>
          </div>
          
          {isImporting ? (
            <div className="space-y-3">
              <div className="w-full bg-slate-100 h-2.5 rounded-full overflow-hidden">
                <div 
                  className="bg-indigo-600 h-full transition-all duration-300"
                  style={{ width: `${progress}%` }}
                />
              </div>
              <div className="flex items-center justify-center gap-2 text-indigo-600 font-bold text-sm">
                <Loader2 size={16} className="animate-spin" />
                <span>جاري الاستيراد... {progress}%</span>
              </div>
            </div>
          ) : (
            <button 
              onClick={handleImport}
              className="px-8 py-3 bg-indigo-600 text-white rounded-2xl font-bold shadow-xl shadow-indigo-100 hover:bg-indigo-700 transition-all"
            >
              بدء الاستيراد الآن
            </button>
          )}
        </div>
      ) : (
        <div className="space-y-4 animate-in fade-in zoom-in duration-300">
          <div className="w-16 h-16 bg-green-50 rounded-full flex items-center justify-center mx-auto">
            <CheckCircle2 size={32} className="text-green-600" />
          </div>
          <div>
            <h3 className="text-lg font-bold text-slate-900">اكتمل الاستيراد!</h3>
            <div className="flex justify-center gap-4 mt-2">
              <div className="px-4 py-2 bg-green-50 text-green-700 rounded-xl text-sm font-bold border border-green-100">
                تم استيراد: {result.success}
              </div>
              <div className="px-4 py-2 bg-amber-50 text-amber-700 rounded-xl text-sm font-bold border border-amber-100">
                تخطي (موجود مسبقاً): {result.skipped}
              </div>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
